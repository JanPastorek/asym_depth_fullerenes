function get_automorphism(g::NautyGraph)
    n = nv(g)
    # To find a non-trivial automorphism, we can try mapping vertex 1 to vertex j (j > 1)
    # and check if there's an isomorphism.
    # We use vertex coloring to distinguish the mapped vertices.
    
    for j in 2:n
        # Create a coloring where vertex 1 and vertex j are uniquely colored
        # NautyGraphs.nauty supports a partition (coloring).
        # Labels are 0-indexed in nauty, but NautyGraphs might handle it.
        # Let's try a simpler approach: use canonical_id with colored vertices if possible.
        # Since NautyGraphs doesn't easily support coloring in the high-level API,
        # we can try a hack: add a "pendant" vertex to 1 and another to j.
        
        g1 = Graphs.copy(g)
        add_vertex!(g1)
        add_edge!(g1, 1, n+1)
        ng1 = NautyGraph(Graphs.adjacency_matrix(g1))
        
        gj = Graphs.copy(g)
        add_vertex!(gj)
        add_edge!(gj, j, n+1)
        ngj = NautyGraph(Graphs.adjacency_matrix(gj))
        
        if canonical_id(ng1) == canonical_id(ngj)
            # There is an automorphism mapping 1 to j.
            # Now we need the actual permutation.
            # We can find it by getting the canonical labelings.
            # NautyGraphs.nauty returns (canong, group_info) but not the labeling.
            # However, we can use the fact that we found it.
            
            # Since I can't easily get the permutation from NautyGraphs.jl's current API
            # without deeper access to the C library, I will implement a simple 
            # isomorphism check that returns the mapping if it exists, or just 
            # search for the permutation since we know it exists.
            
            # Actually, let's just find the orbit of each vertex.
            # If orbit size > 1, there is an automorphism moving it.
            
            println("Found automorphism mapping vertex 1 to vertex $j")
            # For the purpose of "details", I'll try to find the actual permutation
            # by brute force on the remaining vertices if necessary, but that's slow.
            
            # Let's try to find the smallest permutation.
            return (1, j) # Placeholder for the "move"
        end
    end
    return nothing
end

# Let's use a more robust way to get automorphisms if possible.
# Actually, if I can't get the full permutation, I can at least count orbits.

function analyze_subgraph_symmetry(g_full::NautyGraph, comb::Vector{Int})
    subg, vmap = Graphs.induced_subgraph(g_full, comb)
    n_sub = nv(subg)
    _, autg_sub = nauty(subg)
    
    println("Induced subgraph has $(autg_sub.n) automorphisms.")
    
    # Identify moved and fixed vertices.
    # A vertex is fixed if its orbit has size 1.
    # We can check this by coloring each vertex uniquely and seeing if group size changes? 
    # No, we check if mapping v to any other u is possible.
    
    moved = Int[]
    fixed = Int[]
    
    for i in 1:n_sub
        is_fixed = true
        for j in 1:n_sub
            i == j && continue
            
            # Check if there's an automorphism mapping i to j
            gi = Graphs.copy(subg)
            add_vertex!(gi)
            add_edge!(gi, i, n_sub+1)
            ngi = NautyGraph(Graphs.adjacency_matrix(gi))
            
            gj = Graphs.copy(subg)
            add_vertex!(gj)
            add_edge!(gj, j, n_sub+1)
            ngj = NautyGraph(Graphs.adjacency_matrix(gj))
            
            if canonical_id(ngi) == canonical_id(ngj)
                is_fixed = false
                break
            end
        end
        if is_fixed
            push!(fixed, vmap[i])
        else
            push!(moved, vmap[i])
        end
    end
    
    println("Vertices moved: $(length(moved))")
    println("Vertices fixed: $(length(fixed))")
    println("Moved vertex list: $moved")
    # println("Fixed vertex list: $fixed")
end

function find_and_analyze(g6_str::String, target_depth::Int)
    g_simple = Graph6._g6StringToGraph(g6_str)
    g = NautyGraph(Graphs.adjacency_matrix(g_simple))
    n = nv(g)
    
    for i in 1:target_depth
        for comb in combinations(1:n, n - i)
            subg, _ = Graphs.induced_subgraph(g, comb)
            _, autg_sub = nauty(subg)
            if autg_sub.n > 1.0
                println("Found symmetric induced subgraph at depth $i")
                println("Removed vertices: $(setdiff(1:n, comb))")
                analyze_subgraph_symmetry(g, comb)
                return
            end
        end
        
        # Also check for Case 2: two isomorphic subgraphs
        canonical_to_comb = Dict{UInt128, Vector{Int}}()
        for comb in combinations(1:n, n - i)
            subg, _ = Graphs.induced_subgraph(g, comb)
            h = canonical_id(subg)
            if haskey(canonical_to_comb, h)
                comb1 = canonical_to_comb[h]
                comb2 = comb
                println("Found two isomorphic induced subgraphs at depth $i")
                println("Removed in 1: $(setdiff(1:n, comb1))")
                println("Removed in 2: $(setdiff(1:n, comb2))")
                # Details: The "partial automorphism" is the isomorphism between them.
                # Actually the question asks what partial automorphism CAUSED it.
                # In the context of asymmetric depth, if two subsets are isomorphic,
                # any isomorphism between them is a partial automorphism of the original graph.
                # Since Case 1 was found first in my previous run, let's focus on that.
                return
            end
            canonical_to_comb[h] = comb
        end
    end
end

